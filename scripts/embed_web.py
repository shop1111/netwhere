"""Embeds gui/netwhere-ui/web/* into gui/netwhere-ui/web_assets.mbt.

Run after editing the page:  python -I scripts/embed_web.py
With --check it only verifies the generated file is up to date (CI).
While working on the page, `netwhere-ui.exe --web gui\\netwhere-ui\\web`
serves the files directly, without rebuilding.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WEB = os.path.join(ROOT, 'gui', 'netwhere-ui', 'web')
OUT = os.path.join(ROOT, 'gui', 'netwhere-ui', 'web_assets.mbt')


def generate():
    names = sorted(n for n in os.listdir(WEB) if n.endswith(('.html', '.css', '.js', '.svg')))
    parts = [
        '// Generated by scripts/embed_web.py from web\\; do not edit.\n',
        '\n',
        '///|\n',
        '/// The page, by file name.\n',
        'let web_assets : Map[String, String] = Map([\n',
    ]
    for name in names:
        with open(os.path.join(WEB, name), encoding='utf-8') as f:
            text = f.read().replace('\r\n', '\n')
        if text.endswith('\n'):
            text = text[:-1]
        parts.append('  (\n')
        parts.append('    "%s",\n' % name)
        parts.append('    (\n')
        for line in text.split('\n'):
            parts.append('      #|' + line + '\n' if line else '      #|\n')
        parts.append('    ),\n')
        parts.append('  ),\n')
    parts.append('])\n')
    return ''.join(parts)


def main():
    text = generate()
    if '--check' in sys.argv:
        with open(OUT, encoding='utf-8') as f:
            if f.read().replace('\r\n', '\n') != text:
                print('web_assets.mbt is out of date: run python -I scripts/embed_web.py')
                sys.exit(1)
        print('web_assets.mbt is up to date')
        return
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print('wrote', OUT)


main()
